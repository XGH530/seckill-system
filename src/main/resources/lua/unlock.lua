-- =====================================================================
-- 安全释放分布式锁
-- KEYS[1] = 锁 key
-- ARGV[1] = 锁持有者标识（加锁时写入的唯一 value）
--
-- 返回值：
--   1 → 释放成功
--   0 → 锁不存在或不属于当前持有者（不执行删除）
--
-- 【核心考点】为什么必须校验 value？
-- 场景还原：
--   T1: 线程 A 获取锁成功，锁 TTL = 10s
--   T2: 线程 A 业务卡顿（GC / 慢 SQL），15s 后才执行完
--   T3: 10s 时锁自动过期，线程 B 获取到同一把锁
--   T4: 线程 A 执行 DEL lock → 把 B 的锁删掉了！
--   T5: 线程 C 此时也能获取到锁 → 临界区出现两个线程并发 → 超卖
-- 所以"比较再删除"必须原子完成，Lua 是标准做法（Redisson 内部也是这么做的）。
-- =====================================================================

local lockKey = KEYS[1]
local lockValue = ARGV[1]

if redis.call('GET', lockKey) == lockValue then
    return redis.call('DEL', lockKey)
else
    return 0
end
